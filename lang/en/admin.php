| EVERY USER-FACING STRING IN THE ADMIN PANELS.
|
| Filament ships its own translations for its chrome — Save, Delete, Create,
| Search, Dashboard, "Collapse all" — and picks them up from APP_LOCALE on its
| own. What it CANNOT translate is anything we name ourselves: section headings,
| helper texts, and every field label, because Filament derives a missing label
| from the attribute name ("stock_quantity" -> "Stock quantity") in English and
| nothing else. That is what produced a panel half in Bulgarian and half in
| English, and why a field here needs an explicit label even when the English
| reads exactly like the attribute.
|
| Keys are grouped by the panel area they belong to, then by what they are:
|
|   section.*   a Section heading, and section_help.* its description
|   field.*     a component label
|   help.*      a helper text under a field
|   ph.*        a placeholder
|   action.*    a button or repeater add-action label
|
| `shared` is for words that appear in more than one area and must not drift
| apart between them.
*/

